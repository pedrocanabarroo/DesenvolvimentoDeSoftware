    private void btnconsultaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnconsultaActionPerformed

        int idPessoa = Integer.parseInt(txtid.getText());

        PessoaDAO pDAO = new PessoaDAO();

        Pessoa p = pDAO.getPessoa(idPessoa);

        if (p == null) {

            limparFormulario();
            JOptionPane.showMessageDialog(this, "Pessoa não encontrada");

        } else {

            txtid1.setText(String.valueOf(p.getId()));
            txtnome.setText(p.getNome());

            if (p.getSexo().equals("M")) {

                rdo_Masculino.setSelected(true);

            } else {

                rdo_Feminino.setSelected(true);
            }

            cmbIdioma.setSelectedItem(p.getIdioma());

        }
    }//GEN-LAST:event_btnconsultaActionPerformed

    private void btnatualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnatualizarActionPerformed

        String sexo = null;

        if (rdo_Masculino.isSelected()) {

            sexo = "M";

        } else if (rdo_Feminino.isSelected()) {

            sexo = "F";
        }

        Pessoa p = new Pessoa();

        p.setId(Integer.parseInt(txtid1.getText()));
        p.setNome(txtnome.getText());
        p.setSexo(sexo);
        p.setIdioma(cmbIdioma.getSelectedItem().toString());

        PessoaDAO pDAO = new PessoaDAO();
        pDAO.editar(p);

        limparFormulario();

    }//GEN-LAST:event_btnatualizarActionPerformed

    private void limparFormulario() {

        txtid.setText("");
        txtnome.setText("");
        gruposexo.clearSelection();
        cmbIdioma.setSelectedIndex(0);
    }
    private void btnexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnexcluirActionPerformed

        int resposta = JOptionPane.showConfirmDialog(null, "Deseja realmente exlcluir?", "Exclusão", JOptionPane.YES_NO_OPTION);

        if (resposta == JOptionPane.YES_OPTION) {

            PessoaDAO pDAO = new PessoaDAO();
            pDAO.excluir(Integer.parseInt(txtid1.getText()));
            JOptionPane.showMessageDialog(txtid,"ID excluído com sucesso");
        
        
        
        }
        
    }//GEN-LAST:event_btnexcluirActionPerformed

