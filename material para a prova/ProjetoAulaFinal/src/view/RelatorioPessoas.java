    public void preencheTabela() {

        String sexo = "";

        PessoaDAO pDAO = new PessoaDAO();

        if (rdo_Masculino.isSelected()) {

            sexo = "M";

        } else if (rdo_Feminino.isSelected()) {

            sexo = "F";

        } else {

            sexo = "";

        }

        List<Pessoa> listaPessoas = pDAO.getPessoasNome(txtNome.getText(), sexo);

        DefaultTableModel tabelaPessoas = (DefaultTableModel) tbl_Pessoas.getModel();

        tabelaPessoas.setNumRows(0);

        for (Pessoa p : listaPessoas) {

            Object[] obj = new Object[]{
                p.getId(),
                p.getNome(),
                p.getSexo(),
                p.getIdioma()

            };

            tabelaPessoas.addRow(obj);

        }

    }

