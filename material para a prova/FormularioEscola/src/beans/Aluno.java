package beans;

/**
 *
 * @author hermes
 */
public class Aluno {
    
    private int idaluno;
    private String nome;
    private int idade;
    private String curso;

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public int getIdade() {
        return idade;
    }

    public void setIdade(int idade) {
        this.idade = idade;
    }

    public String getCurso() {
        return curso;
    }

    public void setCurso(String curso) {
        this.curso = curso;
    }

    public int getIdaluno() {
        return idaluno;
    }

    public void setIdaluno(int idaluno) {
        this.idaluno = idaluno;
    }

    @Override
    public String toString() {
        return "Aluno{" + "idaluno=" + idaluno + ", nome=" + nome + ", idade=" + idade + ", curso=" + curso + '}';
    }
    
  
    
    
    
}
