    private void btnconsultaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnconsultaActionPerformed

        int id;

        try {
            
            id = Integer.parseInt(txtid.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Informe um ID numérico");
            return;
        }

        AlunoDAO aDAO = new AlunoDAO();
        Aluno a = aDAO.getAluno(id);

        ProfessorDAO pDAO = new ProfessorDAO();
        Professor p = pDAO.getProfessor(id);

        if (a != null) {
            tipoEncontrado = "ALUNO";
            txtid1.setText(String.valueOf(a.getIdaluno()));
            txtnome.setText(a.getNome());
            txtidade.setText(String.valueOf(a.getIdade()));
            txtcurso.setText(a.getCurso());
        } else if (p != null) {
            tipoEncontrado = "PROFESSOR";
            txtid1.setText(String.valueOf(p.getIdProfessor()));
            txtnome.setText(p.getNome());
            txtidade.setText(String.valueOf(p.getIdade()));
            txtcurso.setText(p.getDisciplina());
        } else {
            tipoEncontrado = null;
            limparFormulario();
            JOptionPane.showMessageDialog(this, "Aluno/Professor não encontrado");
        }
    


    }//GEN-LAST:event_btnconsultaActionPerformed

    private void btnatualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnatualizarActionPerformed

        
    int id = Integer.parseInt(txtid1.getText());
    
    String nome = txtnome.getText();
    int idade = Integer.parseInt(txtidade.getText());
    String cursoOuDisc = txtcurso.getText();

    if (isAluno()) {
        Aluno a = new Aluno();
        
        a.setIdaluno(id); 
        a.setNome(nome); 
        a.setIdade(idade); 
        a.setCurso(cursoOuDisc);
        
        new AlunoDAO().editar(a);
        
    } else {
        
        Professor p = new Professor();
        p.setIdProfessor(id); 
        p.setNome(nome); p.setIdade(idade); 
        p.setDisciplina(cursoOuDisc);
        
        new ProfessorDAO().editar(p);
    }
    
    JOptionPane.showMessageDialog(this, "Atualizado com sucesso");
    limparFormulario();

    

    }//GEN-LAST:event_btnatualizarActionPerformed

    public void limparFormulario() {

        cmbTipo.setSelectedIndex(0);
        txtid.setText("");
        txtnome.setText("");
        txtidade.setText("");
        txtcurso.setText("");

    }


    private void btnexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnexcluirActionPerformed

    
     
       
    int resposta = JOptionPane.showConfirmDialog(null, "Deseja realmente excluir?",
                                                 "Exclusão", JOptionPane.YES_NO_OPTION);
    if (resposta != JOptionPane.YES_OPTION) {
        return;
    }

    // 3) Decide qual DAO usar pelo tipo selecionado
    int id = Integer.parseInt(txtid1.getText());

    if (cmbTipo.getSelectedItem().equals("Professor")) {
        new ProfessorDAO().excluir(id);
    } else {
        new AlunoDAO().excluir(id);
    }

    JOptionPane.showMessageDialog(null, "Registro excluído com sucesso");
    limparFormulario();

    }//GEN-LAST:event_btnexcluirActionPerformed

